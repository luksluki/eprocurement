-- 0009_invoices: vendor invoices linked to purchase orders (issue #39, the
-- model + create API; the 3-way match itself is #40). Owned by the
-- procurement service (ADR-0001); no other service writes here. The invoice
-- domain package owns the request-shape validation, the server-side
-- derivation of vendor/currency from the locked PO, the server-side total
-- recompute, and the cumulative over-billing guard; this schema is the
-- storage mirror plus the database backstops (CHECK qty > 0,
-- CHECK unit_price_cents >= 0, UNIQUE (invoice_id, po_item_id), and the
-- status CHECK carrying #40's matched/discrepancy values from day one).
--
-- Column deltas vs the PRD §13 summary row (invoices: id, tenant_id, number,
-- po_id, vendor_id, amount, status, match_result JSONB, created_at),
-- documented in docs/schema/procurement.md:
--   currency         the PO's currency (IDR | USD) — §13 omits it, but every
--                    money field needs its unit; derived server-side from
--                    the locked PO, never client input
--   total_cents      the §13 "amount" as integer cents (same convention as
--                    requisitions/purchase orders), recomputed server-side
--                    from the lines
--   created_by       audit field, same shape as the other procurement tables
--
-- Unlike PR/PO/GRN numbers, the invoice number is NOT generated by this
-- service: it is the vendor's own document number, supplied by the client
-- and unique per (tenant_id, vendor_id) only — the same number from a
-- different vendor is a different invoice (issue #39 technical note).

CREATE TABLE procurement.invoices (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id    uuid NOT NULL,
    po_id        uuid NOT NULL REFERENCES procurement.purchase_orders (id),
    vendor_id    uuid NOT NULL REFERENCES procurement.vendors (id),
    number       text NOT NULL,
    currency     text NOT NULL CHECK (currency IN ('IDR', 'USD')),
    total_cents  bigint NOT NULL,
    status       text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'matched', 'discrepancy')),
    match_result jsonb,
    created_at   timestamptz NOT NULL DEFAULT now(),
    created_by   uuid
);

-- Numbers are unique per (tenant, vendor) — the duplicate-detection rule of
-- issue #39. No ON DELETE CASCADE on po_id or vendor_id: invoices are
-- financial records (the #40 match reads them); deleting a PO or vendor
-- that has invoices must fail, not cascade.
CREATE UNIQUE INDEX invoices_tenant_vendor_number_uidx
    ON procurement.invoices (tenant_id, vendor_id, number);
CREATE INDEX invoices_tenant_idx ON procurement.invoices (tenant_id);
CREATE INDEX invoices_po_idx ON procurement.invoices (po_id);
-- The cumulative over-billing guard sums every invoice of one PO inside the
-- create transaction (under the PO row lock); this index backs that SUM.
CREATE INDEX invoices_po_totals_idx ON procurement.invoices (po_id) INCLUDE (total_cents);

-- invoice_lines mirrors the other item tables (no tenant_id — PRD §13
-- convention; tenancy derives from the parent invoice, transitively from
-- the PO). UNIQUE (invoice_id, po_item_id): one invoice bills each PO line
-- at most once; further billings arrive as further invoices. The qty and
-- price CHECKs are the database twins of the domain's shape validation.
CREATE TABLE procurement.invoice_lines (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    invoice_id       uuid NOT NULL REFERENCES procurement.invoices (id) ON DELETE CASCADE,
    po_item_id       uuid NOT NULL REFERENCES procurement.po_items (id),
    qty              integer NOT NULL CHECK (qty > 0),
    unit_price_cents bigint NOT NULL CHECK (unit_price_cents >= 0),
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (invoice_id, po_item_id)
);

CREATE INDEX invoice_lines_invoice_idx ON procurement.invoice_lines (invoice_id);
CREATE INDEX invoice_lines_po_item_idx ON procurement.invoice_lines (po_item_id);

-- Same RLS pattern as 0001/0003/0007/0008: tenant-scoped policies, forced,
-- and grants for the non-superuser app role. Lines derive tenancy from the
-- parent invoice (transitively from the PO), so isolation stays transitive.

ALTER TABLE procurement.invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE procurement.invoices FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON procurement.invoices
    USING (
        tenant_id::text = current_setting('app.tenant_id', true)
        OR current_setting('app.rls_bypass', true) = 'on'
    )
    WITH CHECK (
        tenant_id::text = current_setting('app.tenant_id', true)
        OR current_setting('app.rls_bypass', true) = 'on'
    );

ALTER TABLE procurement.invoice_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE procurement.invoice_lines FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON procurement.invoice_lines
    USING (
        EXISTS (
            SELECT 1 FROM procurement.invoices i
            WHERE i.id = invoice_lines.invoice_id
              AND (
                i.tenant_id::text = current_setting('app.tenant_id', true)
                OR current_setting('app.rls_bypass', true) = 'on'
              )
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM procurement.invoices i
            WHERE i.id = invoice_lines.invoice_id
              AND (
                i.tenant_id::text = current_setting('app.tenant_id', true)
                OR current_setting('app.rls_bypass', true) = 'on'
              )
        )
    );

GRANT SELECT, INSERT, UPDATE ON procurement.invoices TO eproc_app;
GRANT SELECT, INSERT, UPDATE ON procurement.invoice_lines TO eproc_app;
